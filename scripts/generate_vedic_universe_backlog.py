def main():
    if not os.path.exists(BACKLOG_PATH):
        print(f"Error: Backlog file not found at {BACKLOG_PATH}")
        sys.exit(1)

    with open(BACKLOG_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    target_marker = "## 🏆 TIER 5: HISTORICAL ARCHIVE OF COMPLETED & VERIFIED EPICS"
    if target_marker not in content:
        # Check if Tier 6 or similar
        print(f"Error: Target marker '{target_marker}' not found in backlog.md")
        sys.exit(1)

    # Build the massive section
    section_header = """---

## 🕉️ TIER 5: THE CANONICAL VEDIC UNIVERSE — 189 SCRIPTURE EXPANSION EPICS
*Systematic catalog of 189 canonical sacred scriptures spanning the entire Vedic, Upanishadic, Darshanic, Purāṇic, Itihāsa, Ayurvedic, and Bhakti traditions of Sanatana Dharma. Each epic is fully articulated with granular sub-tasks for multi-tier NVF ingestion, multilingual translations (EN, HI, MR, SA), in-browser bedtime audio podcasts (`podcast-engine.ts`), voice companion anchoring (`voice-host.ts`), and zero-PII seeker affinity tracking.*

"""

    epics_text = "\n".join(generate_epic_markdown(b) for b in BOOKS)

    new_tier_archive_header = "## 🏆 TIER 6: HISTORICAL ARCHIVE OF COMPLETED & VERIFIED EPICS"

    new_section = section_header + epics_text + "\n---\n\n" + new_tier_archive_header

    new_content = content.replace(target_marker, new_section)

    with open(BACKLOG_PATH, 'w', encoding='utf-8') as f:
        f.write(new_content)

    print(f"Successfully generated and inserted {len(BOOKS)} canonical scripture epics into {BACKLOG_PATH}")

if __name__ == "__main__":
    main()
